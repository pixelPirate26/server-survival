#!/usr/bin/env node

const fs = require("fs");
const path = require("path");

const frontendDir = path.resolve(__dirname, "..");
const envPath = path.join(frontendDir, ".env");
const outputPath = path.join(frontendDir, "env-config.js");

function parseEnvFile(contents) {
  const result = {};
  const lines = contents.split(/\r?\n/);

  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) {
      continue;
    }

    const separatorIndex = trimmed.indexOf("=");
    if (separatorIndex <= 0) {
      continue;
    }

    const key = trimmed.slice(0, separatorIndex).trim();
    let value = trimmed.slice(separatorIndex + 1).trim();

    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }

    result[key] = value;
  }

  return result;
}

const defaultApiUrl = "http://localhost:8787/api";
let apiUrl = defaultApiUrl;

if (fs.existsSync(envPath)) {
  const envContents = fs.readFileSync(envPath, "utf8");
  const envMap = parseEnvFile(envContents);
  if (typeof envMap.SERVER_API_URL === "string" && envMap.SERVER_API_URL.trim()) {
    apiUrl = envMap.SERVER_API_URL.trim();
  }
}

const normalizedApiUrl = apiUrl.replace(/\/+$/, "");
const output = `// Auto-generated by scripts/generate-env-config.js
window.SERVER_API_URL = ${JSON.stringify(normalizedApiUrl)};
`;

fs.writeFileSync(outputPath, output, "utf8");
console.log(`Wrote ${path.relative(frontendDir, outputPath)} with SERVER_API_URL=${normalizedApiUrl}`);

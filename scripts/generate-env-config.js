#!/usr/bin/env node

const fs = require("fs");
const path = require("path");

const frontendDir = path.resolve(__dirname, "..");
const envPath = path.join(frontendDir, ".env");
const defaultOutputPath = path.join(frontendDir, "env-config.js");

function parseEnvFile(contents) {
  const result = {};
  const lines = contents.split(/\r?\n/);

  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) {
      continue;
    }

    const separatorIndex = trimmed.indexOf("=");
    if (separatorIndex <= 0) {
      continue;
    }

    const key = trimmed.slice(0, separatorIndex).trim();
    let value = trimmed.slice(separatorIndex + 1).trim();

    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }

    result[key] = value;
  }

  return result;
}

function resolveApiUrl() {
  const defaultApiUrl = "http://localhost:8787/api";
  const envValue = typeof process.env.SERVER_API_URL === "string" ? process.env.SERVER_API_URL.trim() : "";

  if (envValue) {
    return envValue.replace(/\/+$/, "");
  }

  if (fs.existsSync(envPath)) {
    const envContents = fs.readFileSync(envPath, "utf8");
    const envMap = parseEnvFile(envContents);
    if (typeof envMap.SERVER_API_URL === "string" && envMap.SERVER_API_URL.trim()) {
      return envMap.SERVER_API_URL.trim().replace(/\/+$/, "");
    }
  }

  return defaultApiUrl;
}

function writeEnvConfig(outputPath = defaultOutputPath) {
  const normalizedApiUrl = resolveApiUrl();
  const output = `// Auto-generated by scripts/generate-env-config.js
window.SERVER_API_URL = ${JSON.stringify(normalizedApiUrl)};
`;

  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, output, "utf8");

  return {
    outputPath,
    normalizedApiUrl,
  };
}

if (require.main === module) {
  const cliOutputPath = process.argv[2]
    ? path.resolve(process.cwd(), process.argv[2])
    : defaultOutputPath;
  const result = writeEnvConfig(cliOutputPath);
  console.log(
    `Wrote ${path.relative(frontendDir, result.outputPath)} with SERVER_API_URL=${result.normalizedApiUrl}`
  );
}

module.exports = {
  parseEnvFile,
  resolveApiUrl,
  writeEnvConfig,
};
